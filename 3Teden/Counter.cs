namespace Counter
{
    internal class Program
    {
        static void Main(string[] args)
        {
            for (int i = -3; i <= 3; i++)
            {
                Console.WriteLine(i);
            }
            int j = -3;
            while(j <= 3)
            {
                Console.WriteLine(j);
                j++;
            }
        }
    }
}
